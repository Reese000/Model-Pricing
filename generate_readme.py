import json

with open('openrouter_models_with_cache.json', 'r') as f:
    data = json.load(f)

models = data['models']

# Sort by cache_read_per_M
models.sort(key=lambda m: m['cache_read_per_M'])

# Identify coding/reasoning models
coding_keywords = [
    'code', 'coder', 'codestral', 'devstral', 'kat-coder', 'mimo', 'deepseek', 'gemini',
    'claude', 'gpt', 'grok', 'qwen', 'mistral', 'llama', 'hermes', 'kimi', 'nex-n',
    'nemotron', 'seed', 'longcat', 'mercury', 'ling', 'ring', 'solar', 'phi',
    'granite', 'laguna', 'aion', 'saba', 'minimax-m', 'cogito', 'write', 'fugu',
    'palmyra', 'step', 'hy3', 'cydonia', 'rocinante', 'skyfall', 'unslopnemo',
    'trinity', 'virtuoso', 'inkling', 'perceptron', 'olmo', 'jamba'
]
exclude_keywords = ['image', 'safety', 'guard', 'search', 'audio', 'lyria']

candidates = []
for m in models:
    mid = m['id'].lower()
    is_coding = any(kw in mid for kw in coding_keywords)
    is_excluded = any(x in mid for x in exclude_keywords)
    if is_coding and not is_excluded:
        candidates.append(m)

lines = []
lines.append('# OpenRouter Model Pricing \u2014 Cache Hit Comparison')
lines.append('')
lines.append('## About this project')
lines.append('')
lines.append('A reference table of OpenRouter model pricing with a focus on **cache hit discounts** '
            '(`input_cache_read` pricing). This project fetches the [OpenRouter models API]'
            '(https://openrouter.ai/api/v1/models), filters for models that offer cache pricing, '
            'and ranks them by cache-read cost per million tokens \u2014 making it easy to spot '
            'the cheapest cached-inference options for coding and reasoning workloads.')
lines.append('')
lines.append('Data is sourced from the public OpenRouter API. The raw API response lives in '
            '`openrouter_models_raw.json` (regeneratable), and the filtered cache-pricing subset '
            'lives in `openrouter_models_with_cache.json`. This README is auto-generated by '
            '`generate_readme.py` \u2014 do not edit the table sections by hand.')
lines.append('')
lines.append('> **Relationship note:** This project shares its data source (OpenRouter API) with '
            'the [OpenRouter_Analysis](../OpenRouter_Analysis/) project in the same workspace, '
            'but is an independent snapshot/visualization focused purely on cache-hit pricing.')
lines.append('')
lines.append(f'**Fetched:** 2026-07-23 from https://openrouter.ai/api/v1/models')
lines.append(f'**Total models with cache pricing:** {len(models)}')
lines.append(f'**Coding/reasoning models shown:** {len(candidates)}')
lines.append('')
lines.append('> Cache hit pricing (`input_cache_read`) is the cost when prompt prefix is cached.')
lines.append('> Discount % = how much cheaper cache hit is vs full prompt price.')
lines.append('')
lines.append('| # | Model ID | Name | Prompt $/M | Comp $/M | **Cache Rd $/M** | Disc % | Context |')
lines.append('|---|----------|------|-----------|---------|----------------|-------|--------|')

for i, m in enumerate(candidates):
    ctx = f"{m['context']:,}" if m['context'] else 'N/A'
    name = m['name'][:40]
    lines.append(
        f"| {i+1} | `{m['id']}` | {name} | ${m['prompt_per_M']:.4f} | "
        f"${m['completion_per_M']:.4f} | **${m['cache_read_per_M']:.6f}** | "
        f"{m['discount_pct']}% | {ctx} |"
    )

lines.append('')
lines.append('---')
lines.append('')
lines.append('### Full table (all 184 models with cache pricing, sorted by cache Rd $/M)')
lines.append('')
lines.append('| # | Model ID | Prompt $/M | Comp $/M | **Cache Rd $/M** | Disc % | Ctx |')
lines.append('|---|----------|-----------|---------|----------------|-------|-----|')

for i, m in enumerate(models):
    ctx = f"{m['context']:,}" if m['context'] else 'N/A'
    lines.append(
        f"| {i+1} | `{m['id']}` | ${m['prompt_per_M']:.4f} | "
        f"${m['completion_per_M']:.4f} | **${m['cache_read_per_M']:.6f}** | "
        f"{m['discount_pct']}% | {ctx} |"
    )

lines.append('')
lines.append('---')
lines.append('')
lines.append(f'*Generated 2026-07-23. {len(models)} models with `input_cache_read` pricing.*')

with open('README.md', 'w') as f:
    f.write('\n'.join(lines) + '\n')

print(f"Written README.md with {len(candidates)} coding models and {len(models)} total")
print()
print("Top 20 cheapest cache-hit models (coding/reasoning):")
print(f"{'Rank':<6} {'Model ID':<50} {'Cache Rd $/M':<16} {'Prompt $/M':<14}")
print("-" * 90)
for i, m in enumerate(candidates[:20]):
    print(f"{i+1:<6} {m['id']:<50} ${m['cache_read_per_M']:<10.6f}  ${m['prompt_per_M']:<8.4f}")
